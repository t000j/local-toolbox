// Portable static guardrails only; Windows behavior is covered by the separate
// opt-in synthetic-fixture script. This script never scans user directories.
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = path.join(__dirname, '..', 'src-tauri', 'src')
const rust = fs.readFileSync(path.join(base, 'file_scan.rs'), 'utf8')
const script = fs.readFileSync(path.join(base, 'native_scripts', 'file_scan.ps1'), 'utf8')
const runner = fs.readFileSync(path.join(base, 'network_probe.rs'), 'utf8')
let checks = 0
function check(value, message) { assert.ok(value, message); checks++ }
const compact = script.split(/\r?\n/).map(line => line.trim()).filter(line => line && !line.startsWith('#') && !line.startsWith('//')).join('\n')
const source = runner.match(/let source = format!\("((?:\\.|[^"\\])*)"\);/)
check(source, 'fixed runner wrapper remains inspectable')
const wrapped = JSON.parse('"' + source[1] + '"').replaceAll('{{', '{').replaceAll('}}', '}').replace('{script}', compact)
const commandChars = Buffer.from(wrapped, 'utf16le').toString('base64').length + 300
check(commandChars < 32767, 'actual wrapper plus 300-character executable/argument allowance fits CreateProcessW')
check((compact.length + 700) * 8 / 3 + 300 < 32767, 'Rust conservative command-length guard passes')
check(rust.includes('deny_unknown_fields'), 'request rejects undeclared fields')
check(rust.includes('after_ms: Option<i64>'), 'dates retain signed Windows epoch bounds')
check(rust.includes('Duration::from_secs(30)'), '30-second outer deadline')
check(rust.indexOf('let lease = acquire_job(&job_id)?') < rust.indexOf('let request = validate(request)?'), 'claim reservation before validation')
check(rust.includes('execute_script(&lease, &compact_script(), &input'), 'fixed source with JSON stdin')
check(script.includes('NtCreateFile(out raw,0x100080U|((dir||data)?1U:0U),ref oa,out io,IntPtr.Zero,0,1,1,0x600020U|(dir?1U:0x40U)'), 'read-only, read-share-only, existing-only, relative no-follow opens')
check(script.includes('root=parent.DangerousGetHandle(),name=ptr,attrs=0x1000'), 'exact-case directory-relative open and do-not-reparse flags')
check(script.includes('GetFileInformationByHandleEx(dir.h,first?15:14'), 'handle-based directory enumeration')
check(script.includes('held.Add(h)'), 'directory handles retained')
check(script.includes('if((i.attrs&Blocked)!=0)'), 'opened handle reparse/offline check')
check(script.includes('GetFinalPathNameByHandle(h,final,1024,0)'), 'drive aliases fail closed')
check(script.includes('visited>=10000') && script.includes('parent.depth>=32') && script.includes('dirs.Count>=1000'), 'traversal bounds')
check(script.includes('rows>=1000') && script.includes('outputBytes+bytes>55*1024'), 'row and output bounds')
check(script.includes('64L*1024*1024') && script.includes('512L*1024*1024'), 'per-file and total hash-byte bounds')
check(script.includes('list.Count<2') && script.includes('SHA256.Create()'), 'size groups precede real SHA-256')
check((script.match(/Same\(item,Check\(h,false\),Change\(h\)\)/g) || []).length === 2, 'identity and metadata checked before and after hashing')
check(script.includes('new FileStream(h,FileAccess.Read'), 'hashing uses verified opened handle')
check(script.includes('Console.Out.Flush()'), 'completed rows flush immediately')
check(script.includes('e is ScanFault?e.Message:"io-error"'), 'system error messages cannot become unbounded summary keys')
check(script.includes('issues.Count<8') && script.includes('path.Length>120'), 'example error paths are bounded')
check(script.includes('summary=true,visited=scan.visited,skipped=scan.skipped,limited='), 'summary contract')
check(!/Get-ChildItem|Directory\.Enumerate|File\.Open|Invoke-Expression|Remove-Item|Move-Item|DeleteFile|WriteFile/.test(script), 'no path-based recursion, reopen, evaluation, or write actions')
console.log(`${checks} scanner source checks passed; compact source ${compact.length} UTF-16 units; actual encoded command + allowance ${commandChars}/32767 characters`)
